import { useCallback, useEffect, useRef, useState } from 'react';
import { Link, useNavigate, useParams } from 'react-router';
import { useAuth } from '../../auth/AuthContext.jsx';
import { loadCandidateLookups } from '../../api/lookups.js';
import EmptyState from '../../components/EmptyState.jsx';
import ErrorState from '../../components/ErrorState.jsx';
import { FormGrid } from '../../components/FormField.jsx';
import FormPanel from '../../components/FormPanel.jsx';
import LoadingState from '../../components/LoadingState.jsx';
import Notice from '../../components/Notice.jsx';
import PageHeader from '../../components/PageHeader.jsx';
import { useApi } from '../../hooks/useApi.js';
import { createCandidate, getCandidate, previewCandidateId, updateCandidate } from './api.js';
import {
  applyExtraction,
  fillFields,
  matchLookup,
  reviewNotes,
  positionSuggestion as suggestPosition,
} from './cvFill.js';
import CvReader from './CvReader.jsx';
import DuplicateWarning from './DuplicateWarning.jsx';
import { isLinkedinProfileUrl } from './linkedin.js';
import { CANDIDATE_FIELDS } from './fields.js';

const EMPTY_VALUES = Object.fromEntries(CANDIDATE_FIELDS.map((field) => [field.name, '']));
const NO_CANDIDATE = async () => ({ ok: true, status: 200, body: null });

const EMAIL_SHAPE = /^[^@\s]+@[^@\s]+\.[^@\s]+$/;
const PHONE_SHAPE = /^\+?[0-9]{9,15}$/;
const URL_SHAPE = /^https?:\/\/\S+$/i;

// Quick checks for the user's convenience. The backend checks everything
// again and has the final say.
function validate(values) {
  const errors = {};
  if (!values.fullName.trim()) errors.fullName = 'Name is required.';

  const phone = values.phone.replace(/[\s\-().]/g, '');
  if (phone && !PHONE_SHAPE.test(phone)) {
    errors.phone = 'Phone must be 9 to 15 digits, with an optional + at the start.';
  }
  if (values.email.trim() && !EMAIL_SHAPE.test(values.email.trim())) {
    errors.email = 'Email is not a valid address.';
  }
  if (values.linkedinUrl.trim() && !isLinkedinProfileUrl(values.linkedinUrl)) {
    errors.linkedinUrl =
      'Enter a LinkedIn profile address, such as https://www.linkedin.com/in/your-name.';
  }
  for (const [name, label] of [
    ['cvUrl', 'CV Link'],
    ['companyCvUrl', 'Company CV Link'],
  ]) {
    if (values[name].trim() && !URL_SHAPE.test(values[name].trim())) {
      errors[name] = `${label} must be a web address starting with http:// or https://.`;
    }
  }
  return errors;
}

function toFormValues(candidate) {
  const values = { ...EMPTY_VALUES };
  for (const { name } of CANDIDATE_FIELDS) {
    const value = candidate[name];
    values[name] = value === null || value === undefined ? '' : String(value);
  }
  return values;
}

// The Candidate ID is generated by the backend, so it is never sent.
// The Candidate ID is generated by the backend, and the LinkedIn link and the
// second phone number have no database field yet, so none of them is sent.
function toPayload(values) {
  const payload = { ...values };
  delete payload.candidateCode;
  delete payload.linkedinUrl;
  delete payload.phone2;
  return {
    ...payload,
    positionId: values.positionId ? Number(values.positionId) : null,
    sourceId: values.sourceId ? Number(values.sourceId) : null,
  };
}

// Active values, plus the candidate's current value even if it has since been
// switched off, so an old record still shows what it holds.
function lookupOptions(items, currentId) {
  return items
    .filter((item) => item.isActive || String(item.id) === currentId)
    .map((item) => ({
      value: String(item.id),
      label: item.isActive ? item.name : `${item.name} (no longer in use)`,
    }));
}

// Used for both Add Candidate and Edit Candidate.
export default function CandidateFormPage({ page }) {
  const { id } = useParams();
  const isEdit = Boolean(id);
  const navigate = useNavigate();
  const { user } = useAuth();
  const mayEdit = (user?.permissions ?? []).includes('candidates.edit');

  const lookups = useApi(loadCandidateLookups, []);
  const existing = useApi(() => (isEdit ? getCandidate(id) : NO_CANDIDATE()), [id]);

  const [values, setValues] = useState(EMPTY_VALUES);
  const [errors, setErrors] = useState({});
  const [duplicates, setDuplicates] = useState(null);
  const [saving, setSaving] = useState(false);
  const [saveError, setSaveError] = useState(null);
  // Set when the details were filled in from a CV; the saved candidate is then
  // confirmed on this page (with its Candidate ID and links) instead of moving on.
  const [fromCv, setFromCv] = useState(false);
  const [registered, setRegistered] = useState(null);
  // A LinkedIn link was entered when the candidate was saved, but it cannot be stored yet.
  const [linkedinDropped, setLinkedinDropped] = useState(false);
  // Likewise for a second phone number.
  const [phone2Dropped, setPhone2Dropped] = useState(false);
  // Short messages under fields where the CV was genuinely ambiguous.
  const [notes, setNotes] = useState({});
  // What CVs put into the form, to tell it apart from what HR typed.
  const autoFilled = useRef({});
  // The form's current values, kept alongside the state. A CV read finishes later
  // than the click that started it, so it must work from the values as they are
  // NOW. The new values and the "what a CV filled" record are worked out here,
  // outside any state updater: React StrictMode (which the app runs in) calls an
  // updater twice, and a record changed inside it is wrong the second time.
  const valuesRef = useRef(EMPTY_VALUES);
  valuesRef.current = values; // after any other change to the state (loading, resetting)
  // Stores a fill result: the new values and the updated record of what CVs filled.
  // "merge" adds to the record instead of replacing it.
  function commit(result, { merge = false } = {}) {
    autoFilled.current = merge
      ? { ...autoFilled.current, ...result.autoFilled }
      : result.autoFilled;
    valuesRef.current = result.values;
    setValues(result.values);
  }
  // The newest lookup lists, for a CV read that finishes after a re-render.
  const lookupLists = useRef({ positions: [], sources: [] });
  // Stops a quick double click from sending the save twice.
  const inFlight = useRef(false);
  // The Candidate ID the next save would get. Only a preview: nothing is
  // reserved, and the saved candidate shows the ID the backend really assigned.
  // It stays empty until a CV has been read, and is cleared again if reading
  // fails or the CV is removed.
  const [previewId, setPreviewId] = useState(null);
  const previewRequest = useRef(0);
  // What to tell HR about the Applied Position, and lists fetched since.
  const [positionSuggestion, setPositionSuggestion] = useState(null);
  // The last CV read named no position at all (so the dropdown stays empty).
  const [noPositionFound, setNoPositionFound] = useState(false);
  const [freshLists, setFreshLists] = useState(null);
  const mayAddPositions = (user?.permissions ?? []).includes('admin.manage');

  const loadPreview = useCallback(() => {
    if (isEdit || !mayEdit) return;
    previewRequest.current += 1;
    const mine = previewRequest.current;
    previewCandidateId()
      .then(
        (res) => res.ok && mine === previewRequest.current && setPreviewId(res.body.candidateCode),
      )
      .catch(() => {});
  }, [isEdit, mayEdit]);
  const clearPreview = useCallback(() => {
    previewRequest.current += 1; // an answer still on its way is ignored
    setPreviewId(null);
  }, []);

  // When editing, fill the form once the candidate has arrived.
  useEffect(() => {
    if (existing.status === 'ready' && existing.data) {
      setValues(toFormValues(existing.data.candidate));
    }
  }, [existing.status, existing.data]);

  function handleChange(name, value) {
    valuesRef.current = { ...valuesRef.current, [name]: value };
    setValues(valuesRef.current);
    setErrors((old) => ({ ...old, [name]: undefined }));
    setNotes((old) => ({ ...old, [name]: undefined }));
    if (name === 'positionId') {
      setPositionSuggestion(null);
      setNoPositionFound(false);
    }
    // Any edit after a duplicate warning means it must be checked again.
    setDuplicates(null);
  }

  // A CV link was pasted: it goes into the CV Link field straight away.
  function linkSupplied(url) {
    commit(
      fillFields({
        values: valuesRef.current,
        autoFilled: autoFilled.current,
        found: { cvUrl: url },
        clearStale: false,
      }),
      { merge: true },
    );
  }

  // The backend read a CV: fill in what it found. HR's own entries are kept.
  function cvRead(body) {
    setFromCv(true);
    commit(
      applyExtraction({
        values: valuesRef.current,
        autoFilled: autoFilled.current,
        body,
        lookups: lookupLists.current,
      }),
    );
    setNotes(reviewNotes(body.extraction));
    setPositionSuggestion(suggestPosition(body.extraction, lookupLists.current));
    setNoPositionFound(
      !body.extraction.hints?.appliedPosition && !body.extraction.hints?.targetPosition,
    );
    loadPreview();
    setErrors({});
    setDuplicates(null);
  }

  // Reading a CV failed: no CV is applied, so there is no ID to preview.
  function cvFailed() {
    setNoPositionFound(false);
    clearPreview();
  }

  // HR removed the CV: its preview and suggestion go, and so do the values it
  // filled in that HR has not changed. Anything HR typed stays.
  function cvRemoved() {
    clearPreview();
    setPositionSuggestion(null);
    setNoPositionFound(false);
    setNotes({});
    setFromCv(false);
    commit(
      fillFields({
        values: valuesRef.current,
        autoFilled: autoFilled.current,
        found: {},
        clearStale: true,
      }),
    );
  }

  // Fetches the position and source lists again (for example after an
  // administrator added the position the CV names) and selects that position
  // if it is now in the list and HR has not chosen another.
  async function refreshLists() {
    const res = await loadCandidateLookups().catch(() => null);
    if (!res?.ok) return;
    setFreshLists(res.body);
    lookupLists.current = res.body;
    if (!positionSuggestion) return;
    const found = matchLookup(res.body.positions, positionSuggestion.text);
    if (!found) return;
    if (!valuesRef.current.positionId) {
      commit(
        { values: { ...valuesRef.current, positionId: found }, autoFilled: { positionId: found } },
        { merge: true },
      );
    }
    setPositionSuggestion(null);
  }

  async function save({ confirmDuplicate = false } = {}) {
    if (inFlight.current) return;
    const problems = validate(values);
    setErrors(problems);
    setSaveError(null);
    if (Object.keys(problems).length > 0) return;

    inFlight.current = true;
    setSaving(true);
    let res;
    try {
      const payload = { ...toPayload(values), confirmDuplicate };
      res = await (isEdit ? updateCandidate(id, payload) : createCandidate(payload));
    } catch {
      res = null;
    }
    inFlight.current = false;
    setSaving(false);

    if (res?.ok && !isEdit && fromCv) {
      // Shown only now, after the backend has confirmed the save.
      setLinkedinDropped(values.linkedinUrl.trim() !== '');
      setPhone2Dropped(values.phone2.trim() !== '');
      setRegistered(res.body.candidate);
    } else if (res?.ok) {
      navigate(`/candidates/${res.body.candidate.id}`, {
        state: {
          saved: isEdit
            ? 'Changes saved.'
            : `Candidate added.${
                values.linkedinUrl.trim()
                  ? ' The LinkedIn link was not saved: there is no field for it yet.'
                  : ''
              }`,
        },
      });
    } else if (res?.status === 409) {
      setDuplicates(res.body.duplicates);
    } else if (res?.status === 422) {
      setDuplicates(null);
      setErrors(res.body.fields ?? {});
      setSaveError('Some fields need correcting. Nothing was saved.');
    } else if (res?.status === 403) {
      setSaveError('You do not have permission to save candidates.');
    } else {
      setSaveError('The candidate could not be saved. Check your connection and try again.');
    }
  }

  const header = <PageHeader title={page.label} description={page.description} />;

  // The server refuses the save too; this only spares the user a form they
  // cannot use.
  if (!mayEdit) {
    return (
      <>
        {header}
        <ErrorState
          title="You do not have permission to add or edit candidates"
          message="Ask an administrator if you need access."
        />
      </>
    );
  }

  if (existing.status === 'loading' || lookups.status === 'loading') {
    return (
      <>
        {header}
        <section className="panel">
          <LoadingState />
        </section>
      </>
    );
  }
  if (existing.status === 'not-found') {
    return (
      <>
        {header}
        <section className="panel">
          <EmptyState
            title="Candidate not found"
            message="There is no candidate at this address."
          />
        </section>
      </>
    );
  }
  if (existing.status !== 'ready') {
    return (
      <>
        {header}
        <ErrorState title="The candidate could not be loaded" onRetry={existing.reload} />
      </>
    );
  }

  if (registered) {
    return (
      <>
        {header}
        <Notice tone="success" title="Candidate registered" role="status">
          <p>
            {registered.fullName} was added with Candidate ID{' '}
            <strong>{registered.candidateCode}</strong> and the status Applied.
          </p>
          {linkedinDropped && <p>The LinkedIn link was not saved: there is no field for it yet.</p>}
          {phone2Dropped && (
            <p>Phone Number 2 was not saved: the candidate record has only one phone number.</p>
          )}
          <div className="notice__actions">
            <Link to={`/candidates/${registered.id}`} className="button button--primary">
              View Candidate
            </Link>
            <Link to="/candidates" className="button">
              Candidate List
            </Link>
            <button
              type="button"
              className="button"
              onClick={() => {
                setRegistered(null);
                setLinkedinDropped(false);
                setPhone2Dropped(false);
                setFromCv(false);
                setValues(EMPTY_VALUES);
              }}
            >
              Add another candidate
            </button>
          </div>
        </Notice>
      </>
    );
  }

  const loaded = lookups.status === 'ready' ? lookups.data : { positions: [], sources: [] };
  const lists = freshLists ?? loaded;
  lookupLists.current = lists;
  const noValuesHint = (what) =>
    `No ${what} have been defined yet. An administrator can add them under Administration → Positions & Sources.`;
  // A position the CV gives that is in no option, shown beside the dropdown.
  const positionHint = positionSuggestion ? (
    <>
      {`Suggested from CV: ${positionSuggestion.text}. `}
      It is not in the position list. Choose an existing position.{' '}
      {mayAddPositions ? (
        <>
          <Link to="/admin/lookups" target="_blank" rel="noreferrer">
            Add New Position
          </Link>
          {' · '}
          <button type="button" className="button" onClick={refreshLists}>
            Refresh list
          </button>
        </>
      ) : (
        'You do not have permission to add positions; ask an administrator if it is needed.'
      )}
    </>
  ) : noPositionFound ? (
    'No applied position was found in the CV. Choose one.'
  ) : null;
  // The LinkedIn link and the second phone number have nowhere to be stored yet,
  // so an existing candidate's form does not offer them.
  const formFields = CANDIDATE_FIELDS.filter(
    (field) => !(isEdit && (field.name === 'linkedinUrl' || field.name === 'phone2')),
  );
  const fields = formFields
    .map((field) => {
      if (field.name === 'positionId') {
        const options = lookupOptions(lists.positions, values.positionId);
        return {
          ...field,
          options,
          hint: options.length === 0 ? noValuesHint('positions') : undefined,
        };
      }
      if (field.name === 'candidateCode') return { ...field, disabled: true };
      if (field.name === 'sourceId') {
        const options = lookupOptions(lists.sources, values.sourceId);
        return {
          ...field,
          options,
          hint: options.length === 0 ? noValuesHint('sources') : undefined,
        };
      }
      return field;
    })
    .map((field) => (notes[field.name] ? { ...field, hint: notes[field.name] } : field))
    .map((field) =>
      field.name === 'positionId' && positionHint && !values.positionId
        ? { ...field, hint: positionHint }
        : field,
    );

  return (
    <>
      {header}

      {lookups.status !== 'ready' && (
        <Notice>
          The position and source lists could not be loaded, so those two fields are empty.
        </Notice>
      )}
      {saveError && (
        <Notice tone="danger" role="alert">
          {saveError}
        </Notice>
      )}
      {duplicates && (
        <DuplicateWarning
          duplicates={duplicates}
          saving={saving}
          onConfirm={() => save({ confirmDuplicate: true })}
          onCancel={() => setDuplicates(null)}
        />
      )}

      {!isEdit && (
        <CvReader
          onLink={linkSupplied}
          onExtracted={cvRead}
          onFailed={cvFailed}
          onRemoved={cvRemoved}
          disabled={saving}
        />
      )}

      <FormPanel
        cancelTo={isEdit ? `/candidates/${id}` : '/candidates'}
        onSubmit={() => save()}
        saving={saving}
      >
        <FormGrid
          fields={fields}
          values={{
            ...values,
            candidateCode: isEdit ? values.candidateCode : (previewId ?? ''),
          }}
          errors={errors}
          onChange={handleChange}
          disabled={saving}
        />
      </FormPanel>
    </>
  );
}
