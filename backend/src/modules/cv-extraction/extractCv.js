// Phase 1 of CV extraction: a CV file in, a reviewable result out.
//
// The result is a DRAFT for the Candidate Registration form. Nothing here
// creates or changes a candidate, invents a Candidate ID, or reads the
// database. Extraction is local: no CV text leaves this process.

import { validateCandidate } from '../candidates/candidates.validation.js';
import { extractCvText } from './textExtractor.js';
import { extractFields } from './fieldExtractor.js';
import { findLinkedin } from './linkedin.js';

// The form fields extraction can fill. Names match validateCandidate().
export const EXTRACTABLE_FIELDS = [
  'fullName',
  'phone',
  'email',
  'address',
  'olMaths',
  'alResult',
  'alStream',
  'otherEducation',
];

// Fields the Candidate Registration form needs that extraction never fills.
export const NEVER_EXTRACTED = {
  candidateCode: 'The Candidate ID is generated by the backend when the candidate is saved.',
  positionId: 'Applied Position is chosen from the approved list.',
  sourceId: 'Source is chosen from the approved list.',
  cvUrl: 'The CV link is the link HR pasted, when a link was used.',
  hrComment: 'HR Comment is written by HR.',
};

// Runs the extracted values through the same checks the candidate form uses,
// so a value the form would refuse is flagged here instead of at save time.
function checkWithCandidateRules(fields) {
  const input = {};
  for (const name of EXTRACTABLE_FIELDS) {
    if (fields[name].value !== null) input[name] = fields[name].value;
  }
  const { values, errors } = validateCandidate(input);
  for (const name of EXTRACTABLE_FIELDS) {
    const field = fields[name];
    if (field.value === null) continue;
    if (errors[name]) {
      field.status = 'uncertain';
      field.note = [field.note, `Would be refused by the candidate form: ${errors[name]}`]
        .filter(Boolean)
        .join(' ');
    } else if (values[name] !== null && values[name] !== field.value) {
      // The form tidies this value (for example a phone number's spaces).
      field.original = field.value;
      field.value = values[name];
    }
  }
}

export const failure = (reason, message) => ({
  status: 'failed',
  reason,
  message,
  source: null,
  fields: {},
  formDraft: {},
  review: { unavailable: [], uncertain: [], extracted: [] },
  notExtracted: NEVER_EXTRACTED,
  unmappedSections: [],
  warnings: [],
});

// Reads one CV. `status` is 'extracted' (every field found), 'partial'
// (some missing or uncertain) or 'failed' (the file could not be read; see
// `reason` and `message`).
export async function extractCv({ buffer, allowHtml = false, baseUrl = null, rendered = null }) {
  const read = await extractCvText({ buffer, allowHtml, baseUrl, rendered });
  if (!read.ok) return failure(read.reason, read.message);

  const { fields, hints, unmappedSections, educationSectionFound } = extractFields(read.text, {
    wrapped: read.format === 'pdf',
    links: read.links,
  });
  checkWithCandidateRules(fields);

  // Only values that are explicit in the CV go into the draft. Uncertain
  // values stay in `fields` for review but are not pre-filled.
  const formDraft = {};
  const review = { extracted: [], uncertain: [], unavailable: [] };
  for (const name of EXTRACTABLE_FIELDS) {
    const field = fields[name];
    review[field.status].push(name);
    if (field.status === 'extracted') formDraft[name] = field.value;
  }

  const status = review.extracted.length === EXTRACTABLE_FIELDS.length ? 'extracted' : 'partial';

  // The candidate's LinkedIn profile is optional, so it never makes a CV count
  // as incomplete. It is only read here: no request is ever made to LinkedIn.
  fields.linkedinUrl = findLinkedin(read.text.split('\n'), read.links);
  if (fields.linkedinUrl.status === 'extracted') {
    formDraft.linkedinUrl = fields.linkedinUrl.value;
    review.extracted.push('linkedinUrl');
  } else if (fields.linkedinUrl.status === 'uncertain') {
    review.uncertain.push('linkedinUrl');
  }

  // A second number is offered to HR as Phone Number 2. The candidate record has
  // one phone column, so this is a draft for the form only: it is never merged
  // into the validated phone field.
  const second = fields.phone.alternatives?.[0];
  if (second) {
    const { values, errors } = validateCandidate({ phone: second });
    if (!errors.phone && values.phone) {
      fields.phone2 = { status: 'extracted', value: values.phone, note: null };
      formDraft.phone2 = values.phone;
      review.extracted.push('phone2');
    }
  }

  const warnings = [...read.warnings];
  const educationFound = ['olMaths', 'alResult', 'alStream', 'otherEducation'].some(
    (name) => fields[name].status === 'extracted',
  );
  if (EXTRACTABLE_FIELDS.some((name) => /template text/.test(fields[name].note ?? ''))) {
    warnings.push(
      'This CV has template text instead of some real details; those fields were left empty.',
    );
  }
  if (!educationSectionFound && !educationFound) {
    warnings.push('No "Education" section heading was found, so education fields were not read.');
  }

  return {
    status,
    reason: null,
    message: null,
    source: {
      format: read.format,
      pageCount: read.pageCount,
      characters: read.text.length,
    },
    fields,
    hints,
    formDraft,
    review,
    notExtracted: NEVER_EXTRACTED,
    unmappedSections,
    warnings,
  };
}
